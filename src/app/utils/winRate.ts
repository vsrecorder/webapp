/*
 * 勝率を算出できるか(勝ちか負けで決着した対戦が1件でもあるか)。
 *
 * 勝率は引き分けを分母から外す(勝ち/(勝ち+負け))ため、対戦が1件も無いときだけでなく、
 * 引き分けだけのときも勝率は存在しない。存在しないものを 0.0% として描くと全敗と
 * 見分けが付かないので、表示側はこれで「-」へ切り替える。
 *
 * 記録の戦績(MatchStats)・ユーザーの戦績(UserStatType)・デッキ別の戦績など、
 * 勝ち数と負け数を持つものであれば何にでも使える。
 */
export function hasWinRate(wins: number, losses: number): boolean {
  return wins + losses > 0;
}
